import { serve } from "https://deno.land/std@0.190.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2.49.4";
import { getCorsHeaders, isOriginAllowed } from "../_shared/cors.ts";
import { validateRequest } from "../_shared/validation.ts";
import { withRateLimit } from "../_shared/rateLimit.ts";
import { mapOnboardingRpcError } from "../_shared/onboarding.ts";
import { z } from "https://deno.land/x/zod@v3.22.4/mod.ts";

// Hospital sign-up (roadmap S0-03). Any signed-in account that has NO hospital
// and NO role yet may create one hospital and become its first admin. The
// caller is identified from the JWT only; the tenant id is generated by
// public.create_hospital_with_admin (service role only), which also refuses an
// account that already has a hospital or a role, so this endpoint can never
// move an existing member to another tenant. It used to require the admin
// role, which a brand-new account cannot have, so hospital sign-up was refused.

const requestSchema = z.object({
  name: z.string().min(1),
  address: z.string().optional().nullable(),
  city: z.string().optional().nullable(),
  state: z.string().optional().nullable(),
  zip: z.string().optional().nullable(),
  phone: z.string().optional().nullable(),
  email: z.string().email().optional().nullable(),
  license_number: z.string().optional().nullable(),
});

const handler = async (req: Request): Promise<Response> => {
  const reqCorsHeaders = getCorsHeaders(req);

  if (req.method === "OPTIONS") {
    return new Response(null, { headers: reqCorsHeaders });
  }

  if (!isOriginAllowed(req)) {
    return new Response(
      JSON.stringify({ error: "Origin not allowed" }),
      { status: 403, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  }

  if (req.method !== "POST") {
    return new Response(
      JSON.stringify({ error: "Method not allowed" }),
      { status: 405, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  }

  if (!req.headers.get("Authorization")) {
    return new Response(
      JSON.stringify({ error: "Missing authorization header" }),
      { status: 401, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  }

  const validation = await validateRequest(req, requestSchema);
  if (!validation.success) {
    return new Response(
      JSON.stringify({ error: "Validation failed", details: validation.error }),
      { status: 400, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const supabaseServiceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabaseAnonKey = Deno.env.get("SUPABASE_ANON_KEY")!;

    const authHeader = req.headers.get("Authorization") ?? "";
    const supabaseAuth = createClient(supabaseUrl, supabaseAnonKey, {
      auth: { persistSession: false },
      global: { headers: { Authorization: authHeader } },
    });

    const { data: authData, error: authError } = await supabaseAuth.auth.getUser();
    if (authError || !authData?.user) {
      return new Response(
        JSON.stringify({ error: "Unauthorized" }),
        { status: 401, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
      );
    }

    const supabaseAdmin = createClient(supabaseUrl, supabaseServiceKey, {
      auth: { persistSession: false },
    });

    // Defence in depth (S0-03): enforce "new accounts only" here as well, so
    // this function is safe even if it is deployed before migration
    // 20261105000003 (whose RPC enforces the same rule). Without this, the old
    // RPC would let an existing member create a hospital and move tenants.
    const [{ data: existingProfile, error: profileErr }, { count: roleCount, error: rolesErr }] =
      await Promise.all([
        supabaseAdmin.from("profiles").select("hospital_id").eq("user_id", authData.user.id).maybeSingle(),
        supabaseAdmin.from("user_roles").select("id", { count: "exact", head: true }).eq("user_id", authData.user.id),
      ]);
    if (profileErr || rolesErr) {
      return new Response(
        JSON.stringify({ error: "Could not verify account state" }),
        { status: 500, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
      );
    }
    if (existingProfile?.hospital_id || (roleCount ?? 0) > 0) {
      return new Response(
        JSON.stringify({ error: "This account already belongs to a hospital. Ask an administrator for access." }),
        { status: 409, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
      );
    }

    const { name, address, city, state, zip, phone, email, license_number } = validation.data;

    const { data: hospitalId, error: rpcError } = await supabaseAdmin.rpc(
      "create_hospital_with_admin",
      {
        p_user_id: authData.user.id,
        p_name: name,
        p_address: address ?? null,
        p_city: city ?? null,
        p_state: state ?? null,
        p_zip: zip ?? null,
        p_phone: phone ?? null,
        p_email: email ?? null,
        p_license_number: license_number ?? null,
      }
    );

    if (rpcError) {
      console.error("create_hospital_with_admin error:", rpcError.code);
      const mapped = mapOnboardingRpcError(rpcError, "hospital");
      return new Response(
        JSON.stringify({ error: mapped.error }),
        { status: mapped.status, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
      );
    }

    return new Response(
      JSON.stringify({ success: true, hospital_id: hospitalId }),
      { status: 200, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  } catch (error: unknown) {
    console.error("create-hospital-admin error:", error);
    return new Response(
      JSON.stringify({ error: 'Internal server error' }),
      { status: 500, headers: { "Content-Type": "application/json", ...reqCorsHeaders } }
    );
  }
};

serve((req) => withRateLimit(req, handler));
