#!/usr/bin/env node
/**
 * scripts/db/build-baseline.mjs
 *
 * Turns a live-schema capture (scripts/db/capture-live-schema.sh) into ONE
 * Supabase migration file that recreates the live schema from an empty
 * database. Audit task S0-01; procedure in supabase/baseline/README.md.
 *
 * Usage:
 *   node scripts/db/build-baseline.mjs <capture-dir> [--version YYYYMMDDHHMMSS] [--out <file>]
 *
 * Default output: <capture-dir>/<version>_live_baseline.sql (it is NOT written into
 * supabase/migrations automatically; moving it there is a reviewed step).
 *
 * Transformations of the pg_dump output, and why:
 *   - drops psql meta-commands (\restrict, \unrestrict, \connect ...): the
 *     Supabase CLI sends SQL over the wire and cannot execute them;
 *   - drops session-level SET / set_config lines (search_path = '', row_security
 *     = off, ...): the CLI applies all migrations on one connection, so these
 *     would leak into later migrations. pg_dump schema-qualifies every name, so
 *     search_path is not needed;
 *   - keeps check_function_bodies = false for the baseline only, then RESETs it;
 *   - appends auth.users triggers, storage policies and bucket rows, which live
 *     in Supabase-managed schemas that the public dump does not include.
 */
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const dir = args.find((a) => !a.startsWith('--'));
if (!dir || !fs.existsSync(dir)) {
  console.error('usage: node scripts/db/build-baseline.mjs <capture-dir> [--version YYYYMMDDHHMMSS] [--out <file>]');
  process.exit(2);
}
const val = (n) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const now = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const version = val('--version') || now;
if (!/^\d{14}$/.test(version)) {
  console.error('--version must be 14 digits (YYYYMMDDHHMMSS)');
  process.exit(2);
}
const out = path.resolve(val('--out') || path.join(dir, `${version}_live_baseline.sql`));
const read = (f) => (fs.existsSync(path.join(dir, f)) ? fs.readFileSync(path.join(dir, f), 'utf8') : '');

const schema = read('live_public_schema.sql');
if (!schema.trim()) {
  console.error(`${dir}/live_public_schema.sql is missing or empty`);
  process.exit(2);
}

const SESSION_LINE = /^(SET\s+\w+\s*=|SELECT pg_catalog\.set_config\()/i;
const cleaned = schema
  .split('\n')
  .filter((l) => !/^\\/.test(l)) // psql meta-commands
  .filter((l) => !SESSION_LINE.test(l))
  .join('\n')
  // pg_dump emits CREATE SCHEMA "public" only when told to; Supabase already has it.
  .replace(/^CREATE SCHEMA "public";\s*$/m, '')
  .replace(/\n{3,}/g, '\n\n');

const extensions = read('live_extensions.tsv')
  .split('\n')
  .filter(Boolean)
  .map((l) => l.split('\t'))
  .filter(([name, , schemaName]) => name !== 'plpgsql' && schemaName !== 'pg_catalog')
  .map(([name, , schemaName]) => `CREATE EXTENSION IF NOT EXISTS "${name}" WITH SCHEMA "${schemaName}";`);

const sqlLiteral = (s) => (s === '' || s === undefined ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
const buckets = read('live_storage_buckets.tsv')
  .split('\n')
  .filter(Boolean)
  .map((l) => l.split('\t'))
  .map(
    ([id, pub, size, mimes]) =>
      `INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (${sqlLiteral(id)}, ${sqlLiteral(id)}, ${pub === 't'}, ${size ? Number(size) : 'NULL'}, ${
        mimes ? `ARRAY[${mimes.split(',').map(sqlLiteral).join(', ')}]` : 'NULL'
      }) ON CONFLICT (id) DO NOTHING;`,
  );

// Each storage/auth policy: drop-if-exists first so the baseline stays re-runnable locally.
const policies = read('live_auth_storage_policies.sql')
  .split('\n')
  .filter((l) => l.startsWith('CREATE POLICY'))
  .map((l) => {
    const m = l.match(/^CREATE POLICY ("[^"]+"|\S+) ON (\S+?)\s+AS/);
    return m ? `DROP POLICY IF EXISTS ${m[1]} ON ${m[2]};\n${l}` : l;
  });

const authTriggers = read('live_auth_triggers.sql')
  .replace(/^CREATE TRIGGER (\S+) (.*?) ON auth\.users /gm, (m, name) => `DROP TRIGGER IF EXISTS ${name} ON auth.users;\n${m}`)
  // older captures: make sure every function body is terminated
  .replace(/(\$function\$)[ \t]*$/gm, (m, tag, offset, all) => (all[offset + m.length] === ';' ? m : `${tag};`))
  .replace(/;;/g, ';');

const header = `-- =============================================================================
-- ${path.basename(out)}
-- Live-schema baseline generated by scripts/db/build-baseline.mjs from
-- ${path.relative(process.cwd(), path.resolve(dir))} (captured with scripts/db/capture-live-schema.sh).
-- Replaces the pre-baseline migration history (archived in supabase/migrations_archive/).
-- DO NOT EDIT BY HAND. Regenerate from a new capture instead.
-- =============================================================================

SET check_function_bodies = false;
`;

const body = [
  header,
  '-- ---------------------------------------------------------------- extensions',
  ...extensions,
  '',
  '-- ---------------------------------------------------------------- public schema (pg_dump)',
  cleaned.trim(),
  '',
  '-- ---------------------------------------------------------------- auth.users triggers',
  authTriggers.trim() || '-- none',
  '',
  '-- ---------------------------------------------------------------- storage buckets',
  ...(buckets.length ? buckets : ['-- none']),
  '',
  '-- ---------------------------------------------------------------- auth/storage policies',
  ...(policies.length ? policies : ['-- none']),
  '',
  'RESET check_function_bodies;',
  '',
].join('\n');

fs.writeFileSync(out, body);
console.log(`wrote ${out} (${body.split('\n').length} lines)`);
